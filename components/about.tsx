"use client";

import { useActionState, useState } from "react";
import {
  sendContactMessage,
  type ContactFormState,
} from "@/app/about/actions";
import { useReveal } from "@/lib/use-reveal";

const INITIAL_STATE: ContactFormState = { status: "idle" };

const HIGHLIGHTS = [
  { i: "HEART", t: "HECHO CON ❤️ PARA JUGADORES", c: "magenta" },
  { i: "BROWSER", t: "JUEGOS EN HTML — CORREN EN CUALQUIER NAVEGADOR", c: "cyan" },
  { i: "PLANT", t: "PROYECTO EN CONSTANTE CRECIMIENTO", c: "green" },
] as const;

const ERROR_STYLE = {
  color: "var(--magenta)",
  fontFamily: "var(--mono)",
  fontSize: 11,
  letterSpacing: "0.08em",
} as const;

export function About() {
  useReveal();
  // Cambiar la key remonta el formulario y reinicia useActionState.
  const [formKey, setFormKey] = useState(0);

  return (
    <div className="about fade-in">
      {/* ABOUT */}
      <section className="about-hero">
        <div className="kicker pixel neon-yellow">▸ ACERCA DE</div>
        <h1 className="about-title">ACERCA DE ARCADE VAULT</h1>
        <p className="about-mission">
          ARCADE VAULT nació del amor por los videojuegos clásicos. Nuestra
          misión es preservar y celebrar los arcades que definieron una
          generación, haciéndolos accesibles para todos, en cualquier lugar y
          sin costo.
        </p>

        <div className="highlight-row">
          {HIGHLIGHTS.map((h, i) => (
            <div
              key={i}
              className={"highlight " + h.c}
              style={{ transitionDelay: i * 80 + "ms" }}
            >
              <HighlightIcon kind={h.i} />
              <div className="hl-text pixel">{h.t}</div>
            </div>
          ))}
        </div>
      </section>

      {/* divider banner */}
      <div className="about-divider reveal" aria-hidden="true">
        <div className="div-bar"></div>
        <div className="div-pixels">
          {Array.from({ length: 24 }).map((_, i) => (
            <span key={i} style={{ animationDelay: i * 80 + "ms" }}></span>
          ))}
        </div>
        <div className="div-bar"></div>
      </div>

      {/* CONTACT */}
      <section className="about-contact reveal">
        <div className="contact-grid">
          <div className="contact-intro">
            <div className="kicker pixel neon-cyan">▸ CONTACTO</div>
            <h2 className="contact-title">CONTÁCTANOS</h2>
            <p className="contact-sub">
              ¿Tienes alguna sugerencia, quieres proponer un juego, o
              simplemente quieres saludar? Escríbenos.
            </p>
            <div className="contact-tips">
              <div className="tip">
                <span className="tip-led"></span>RESPUESTA EN 24-48H
              </div>
              <div className="tip">
                <span className="tip-led y"></span>SUGERENCIAS BIENVENIDAS
              </div>
              <div className="tip">
                <span className="tip-led m"></span>SIN SPAM, JAMÁS
              </div>
            </div>
          </div>

          <ContactForm
            key={formKey}
            onReset={() => setFormKey((k) => k + 1)}
          />
        </div>
      </section>
    </div>
  );
}

function ContactForm({ onReset }: { onReset: () => void }) {
  const [state, formAction, pending] = useActionState(
    sendContactMessage,
    INITIAL_STATE,
  );
  const [seen, setSeen] = useState<ContactFormState>(state);
  const [shake, setShake] = useState(false);

  // Cada respuesta nueva con error dispara el shake.
  if (state !== seen) {
    setSeen(state);
    setShake(state.status === "error");
  }

  const values = state.status === "error" ? state.values : undefined;
  const fields = state.status === "error" ? state.fields : undefined;

  return (
    <form
      className={"contact-form" + (shake ? " shake" : "")}
      action={formAction}
      noValidate
      onAnimationEnd={() => setShake(false)}
    >
      {state.status !== "success" ? (
        <>
          <div className="field">
            <label htmlFor="contact-name">NOMBRE</label>
            <input
              id="contact-name"
              name="name"
              defaultValue={values?.name}
              placeholder="px_kai"
              aria-invalid={fields?.name ? true : undefined}
            />
            {fields?.name && <span style={ERROR_STYLE}>{fields.name}</span>}
          </div>
          <div className="field">
            <label htmlFor="contact-email">CORREO ELECTRÓNICO</label>
            <input
              id="contact-email"
              name="email"
              type="email"
              defaultValue={values?.email}
              placeholder="jugador@vault.gg"
              aria-invalid={fields?.email ? true : undefined}
            />
            {fields?.email && <span style={ERROR_STYLE}>{fields.email}</span>}
          </div>
          <div className="field">
            <label htmlFor="contact-msg">MENSAJE</label>
            <textarea
              id="contact-msg"
              name="msg"
              rows={5}
              defaultValue={values?.msg}
              placeholder="Cuéntanos qué tienes en mente…"
              aria-invalid={fields?.msg ? true : undefined}
            ></textarea>
            {fields?.msg && <span style={ERROR_STYLE}>{fields.msg}</span>}
          </div>

          {/* Honeypot: invisible y fuera del orden de tabulación. */}
          <div
            aria-hidden="true"
            style={{
              position: "absolute",
              left: -9999,
              width: 1,
              height: 1,
              overflow: "hidden",
            }}
          >
            <input
              name="website"
              type="text"
              tabIndex={-1}
              autoComplete="off"
              aria-hidden="true"
            />
          </div>

          {state.status === "error" && (
            <div
              role="alert"
              style={{ ...ERROR_STYLE, fontSize: 12, marginBottom: 12 }}
            >
              ✖ {state.message}
            </div>
          )}

          <button
            className="btn xl press"
            type="submit"
            disabled={pending}
            style={{ width: "100%" }}
          >
            {pending ? "ENVIANDO…" : "▶  ENVIAR MENSAJE"}
          </button>
        </>
      ) : (
        <div className="terminal-success">
          <div className="term-bar">
            <span className="dot r"></span>
            <span className="dot y"></span>
            <span className="dot g"></span>
            <span className="term-title">VAULT-OS // TERMINAL</span>
          </div>
          <div className="term-body">
            <div className="line">
              <span className="prompt">vault@arcade:~$</span> ./send_message
              --to=team
            </div>
            <div className="line dim">[OK] Conectando con servidor…</div>
            <div className="line dim">[OK] Validando contenido…</div>
            <div className="line dim">[OK] Transmitiendo paquete…</div>
            <div className="line success">
              &gt; MENSAJE RECIBIDO. TE RESPONDEREMOS PRONTO. GRACIAS,{" "}
              {state.name.toUpperCase()}.<span className="caret">_</span>
            </div>
            <div style={{ marginTop: 18 }}>
              <button className="btn ghost" type="button" onClick={onReset}>
                ENVIAR OTRO MENSAJE
              </button>
            </div>
          </div>
        </div>
      )}
    </form>
  );
}

